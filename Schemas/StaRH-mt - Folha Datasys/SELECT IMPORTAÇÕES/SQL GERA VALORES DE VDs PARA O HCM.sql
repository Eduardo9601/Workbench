SELECT distinct
       B.COD_ORGANOGRAMA,
       A.COD_CONTRATO,
       A.COD_MESTRE_EVENTO,
       --A.COD_VD,
       --TO_CHAR(A.VALOR_VD, 'FM999G999G990D00') AS VALOR_DATASYS
       
       --TO_CHAR(V.VALEVE, 'FM999G999G990D00') AS VALOR_HCM
       
       CASE
           WHEN A.COD_VD = 954 THEN 
             '60,00'
           ELSE
             TO_CHAR(TRUNC(ROUND(A.QTDE_VD * 60) / 60) +
               (MOD(ROUND(A.QTDE_VD * 60), 60) / 100),
               'FM999999999990D00',
               'NLS_NUMERIC_CHARACTERS='',.''') 
       END AS QTDE_VD,
               
       TO_CHAR(A.VALOR_VD, 'FM999G999G990D00') AS VALOR_DATASYS --VD 38

  FROM RHFP1005 A
  JOIN RHFP1003 B
    ON A.COD_MESTRE_EVENTO = B.COD_MESTRE_EVENTO
  LEFT JOIN TB_EVENTOS_VD T
    ON A.COD_VD = T.COD_VD
 WHERE B.COD_EVENTO IN (1, 17, 19)
   AND B.DATA_INI_MOV >= DATE '2026-08-01'
   AND B.DATA_INI_MOV < DATE '2026-09-01'
   AND A.COD_VD = 532--IN (838, 954)
   AND A.VALOR_VD <> 0
   AND B.COD_ORGANOGRAMA = 282
--AND A.COD_CONTRATO <> 391797
 ORDER BY A.COD_CONTRATO;