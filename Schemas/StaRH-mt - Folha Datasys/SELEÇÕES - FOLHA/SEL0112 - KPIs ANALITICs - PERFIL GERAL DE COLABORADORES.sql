/* =====================================================================
   REL0112 - PERFIL DE COLABORADORES
   VERSÃO AJUSTADA PARA BATER COM O ORGANOGRAMA DO SISTEMA

   REGRA-MÃE:
   - A quantidade base de colaboradores nasce do ORGANOGRAMA vigente
     na data de referência, usando RHFP0310 + V_EST_ORG_ALTER_AVT.
   - A V_DADOS_COLAB_AVT entra como enriquecimento cadastral
     para perfil/demografia, não como fonte do afastamento histórico.
   - Afastados usam exatamente a mesma população e os mesmos filtros
     utilizados pelo relatório de turnover na referência.

   Parâmetros:
   :REFERENCIA     = DD/MM/YYYY
   :REDE_EMPRESA   = 8 para empresa geral, ou 1/10/13/30/40/50/70...
===================================================================== */

WITH
PARAMS AS (
    SELECT
        NVL(TO_NUMBER(:REDE_EMPRESA), 8) AS REDE_EMPRESA,
        NVL(TO_DATE(:REFERENCIA, 'DD/MM/YYYY'), TRUNC(SYSDATE)) AS REFERENCIA
    FROM DUAL
),

/* =========================================================
   1. BASE DE CONTRATOS ATIVOS NA REFERÊNCIA
   Regra-mãe: colaborador ativo na REFERENCIA.
   IMPORTANTE: não filtrar V.COD_EMP = 8 aqui, porque o colaborador
   pode estar demitido/movido hoje, mas estava na empresa 8 na referência.
========================================================= */
DADOS_VIEW AS (
    SELECT DISTINCT
           V.COD_PESSOA,
           V.COD_CONTRATO,
           V.DES_PESSOA,
           V.DATA_NASCIMENTO,
           V.DATA_ADMISSAO AS ADMISSAO,
           V.DATA_DEMISSAO,
           V.COD_TIPO_ADMISSAO,
           V.DES_TIPO_ADMISSAO,
           V.SEXO,
           V.COD_EST_CIVIL,
           V.DES_EST_CIVIL,
           V.IND_DEFICIENCIA,
           V.COD_INSTRUCAO,
           V.DES_INSTRUCAO,
           V.COD_PAIS,
           V.COD_PAIS_NASCTO,
           V.COD_NACIONALIDADE,
           V.DES_NACIONALIDADE,
           V.COD_RACA_COR,
           V.DES_RACA_COR,
           NVL(V.COD_AFAST, 0) AS COD_AFAST,
           V.DES_AFAST,
           V.COD_STATUS_AFAST,
           TRIM(UPPER(V.STATUS_AFAST)) AS STATUS_AFAST,
           V.COD_ORGANOGRAMA AS COD_ORGANOGRAMA_VIEW,
           V.COD_UNIDADE AS COD_UNIDADE_VIEW,
           V.DES_UNIDADE AS DES_UNIDADE_VIEW,
           V.COD_REDE_LOCAL AS COD_REDE_LOCAL_VIEW,
           V.DES_REDE_LOCAL AS DES_REDE_LOCAL_VIEW,
           V.COD_EMP AS COD_EMP_VIEW,
           V.DES_EMPRESA AS DES_EMPRESA_VIEW,
           V.COD_UF
    FROM V_DADOS_COLAB_AVT V
    WHERE V.COD_CONTRATO IS NOT NULL
),

DADOS_ATIVOS_REF AS (
    SELECT *
    FROM (
        SELECT
            D.*,
            ROW_NUMBER() OVER (
                PARTITION BY D.COD_CONTRATO
                ORDER BY
                    NVL(D.DATA_DEMISSAO, DATE '2999-12-31') DESC,
                    D.ADMISSAO DESC,
                    D.COD_CONTRATO DESC
            ) AS RN_DADOS
        FROM DADOS_VIEW D
        CROSS JOIN PARAMS P
        WHERE TRUNC(D.ADMISSAO) <= P.REFERENCIA
          AND (
                 D.DATA_DEMISSAO IS NULL
              OR TRUNC(D.DATA_DEMISSAO) >= P.REFERENCIA
          )
    )
    WHERE RN_DADOS = 1
),

/* =========================================================
   2. ORGANOGRAMA VIGENTE NA DATA DE REFERÊNCIA
   Usado para dizer ONDE o colaborador ativo estava na referência.
   Não define sozinho quem é ativo; ele classifica a base ativa.
========================================================= */
ORG_REF AS (
    SELECT *
    FROM (
        SELECT
            H.COD_CONTRATO,
            H.DATA_INICIO AS DATA_INI_ORG,
            H.DATA_FIM    AS DATA_FIM_ORG,
            H.COD_ORGANOGRAMA,

            A.COD_ORG_2 AS COD_EMP,
            A.EDICAO_ORG_2 AS EDICAO_EMP,
            A.NOME2 AS DES_EMPRESA,

            A.EDICAO_ORG AS COD_UNIDADE,
            A.NOME_ORGANOGRAMA_B AS DES_UNIDADE,

            CASE
                WHEN REGEXP_LIKE(TRIM(TO_CHAR(A.COD_REDE)), '^[0-9]+$')
                THEN TO_NUMBER(TRIM(TO_CHAR(A.COD_REDE)))
            END AS COD_REDE_LOCAL,
            A.DES_REDE AS DES_REDE_LOCAL,

            A.DATA_INICIO AS DATA_INI_ESTRUTURA,
            A.DATA_FIM    AS DATA_FIM_ESTRUTURA,

            A.COD_ORG_1, A.EDICAO_ORG_1, A.NOME1,
            A.COD_ORG_2, A.EDICAO_ORG_2, A.NOME2,
            A.COD_ORG_3, A.EDICAO_ORG_3, A.NOME3,
            A.COD_ORG_4, A.EDICAO_ORG_4, A.NOME4,
            A.COD_ORG_5, A.EDICAO_ORG_5, A.NOME5,
            A.COD_ORG_6, A.EDICAO_ORG_6, A.NOME6,
            A.COD_ORG_7, A.EDICAO_ORG_7, A.NOME7,
            A.COD_ORG_8, A.EDICAO_ORG_8, A.NOME8,

            CASE
                WHEN A.COD_ORG_2 = 8 THEN
                    CASE
                        WHEN A.COD_ORG_3 = 9  THEN 2
                        WHEN A.COD_ORG_3 = 21 THEN 3
                        ELSE 1
                    END
                ELSE 4
            END AS COD_TIPO,

            CASE
                WHEN A.COD_ORG_2 = 8 THEN
                    CASE
                        WHEN A.COD_ORG_3 = 9  THEN 'SETOR'
                        WHEN A.COD_ORG_3 = 21 THEN 'DEPÓSITO'
                        ELSE 'LOJA'
                    END
                ELSE 'COLIGADA'
            END AS DES_TIPO,

            ROW_NUMBER() OVER (
                PARTITION BY H.COD_CONTRATO
                ORDER BY
                    H.DATA_INICIO DESC,
                    A.DATA_INICIO DESC,
                    NVL(H.DATA_FIM, DATE '2999-12-31') DESC,
                    NVL(A.DATA_FIM, DATE '2999-12-31') DESC
            ) AS RN_ORG

        FROM DADOS_ATIVOS_REF B
        INNER JOIN RHFP0310 H
            ON H.COD_CONTRATO = B.COD_CONTRATO
        INNER JOIN V_EST_ORG_ALTER_AVT A
            ON A.COD_ORGANOGRAMA = H.COD_ORGANOGRAMA
        CROSS JOIN PARAMS P
        WHERE A.COD_ORG_2 = 8
          AND P.REFERENCIA BETWEEN TRUNC(H.DATA_INICIO)
                              AND NVL(TRUNC(H.DATA_FIM), DATE '2999-12-31')
          AND P.REFERENCIA BETWEEN TRUNC(A.DATA_INICIO)
                              AND NVL(TRUNC(A.DATA_FIM), DATE '2999-12-31')
    )
    WHERE RN_ORG = 1
),


/* =========================================================
   3. AFASTADOS OFICIAIS NA REFERÊNCIA
   Mesma regra/população do turnover.
========================================================= */
AFASTADOS_OFICIAL_REF AS (
    SELECT DISTINCT
        CT.COD_CONTRATO
    FROM V_DADOS_CONTRATO_AVT CT
    INNER JOIN VH_EST_ORG_CONTRATO_AVT ORG
        ON ORG.COD_CONTRATO = CT.COD_CONTRATO
    INNER JOIN VH_CARGO_CONTRATO_AVT FN
        ON FN.COD_CONTRATO = CT.COD_CONTRATO
    INNER JOIN VH_HIST_HORAS_COLAB_AVT HR
        ON HR.COD_CONTRATO = CT.COD_CONTRATO
    INNER JOIN RHFP0306 AF
        ON AF.COD_CONTRATO = CT.COD_CONTRATO
    CROSS JOIN PARAMS P
    WHERE TRUNC(CT.DATA_ADMISSAO) <= P.REFERENCIA
      AND P.REFERENCIA <= NVL(TRUNC(CT.DATA_DEMISSAO), DATE '2999-12-31')

      AND P.REFERENCIA BETWEEN TRUNC(ORG.DATA_INI_ORG)
                           AND NVL(TRUNC(ORG.DATA_FIM_ORG), DATE '2999-12-31')

      AND P.REFERENCIA BETWEEN TRUNC(FN.DATA_INI_CLH)
                           AND NVL(TRUNC(FN.DATA_FIM_CLH), DATE '2999-12-31')

      AND P.REFERENCIA BETWEEN TRUNC(HR.DATA_INI_HR)
                           AND NVL(TRUNC(HR.DATA_FIM_HR), DATE '2999-12-31')

      AND P.REFERENCIA BETWEEN TRUNC(AF.DATA_INICIO)
                           AND NVL(TRUNC(AF.DATA_FIM), DATE '2999-12-31')

      AND ORG.COD_EMP = 8
      AND ORG.EDICAO_ORG_4 IS NOT NULL
      AND NVL(AF.COD_CAUSA_AFAST, 0) NOT IN (0, 7)

      AND UPPER(NVL(FN.DES_FUNCAO, '')) NOT LIKE '%ESTAGIARIO%'
      AND UPPER(NVL(FN.DES_FUNCAO, '')) NOT LIKE '%ESTAGIÁRIO%'
      AND UPPER(NVL(FN.DES_FUNCAO, '')) NOT LIKE '%APRENDIZ%'
      AND UPPER(NVL(FN.DES_FUNCAO, '')) NOT LIKE '%TEMPORARIO%'
      AND UPPER(NVL(FN.DES_FUNCAO, '')) NOT LIKE '%TEMPORÁRIO%'
),

/* =========================================================
   4. FÉRIAS VIGENTES NA REFERÊNCIA
   Férias são separadas dos afastados para garantir:
   TOTAL = TRABALHANDO + FÉRIAS + AFASTADOS.
========================================================= */
FERIAS_REF AS (
    SELECT DISTINCT
        D.COD_CONTRATO
    FROM DADOS_ATIVOS_REF D
    INNER JOIN ORG_REF O
        ON O.COD_CONTRATO = D.COD_CONTRATO
    INNER JOIN RHFP0306 AF
        ON AF.COD_CONTRATO = D.COD_CONTRATO
    CROSS JOIN PARAMS P
    WHERE P.REFERENCIA BETWEEN TRUNC(AF.DATA_INICIO)
                           AND NVL(TRUNC(AF.DATA_FIM), DATE '2999-12-31')
      AND NVL(AF.COD_CAUSA_AFAST, 0) = 7
      AND O.COD_EMP = 8
),

/* =========================================================
   5. BASE FINAL DO REL0112
   Total vem do organograma. Perfil vem da view.
========================================================= */
BASE AS (
    SELECT
        D.COD_PESSOA,
        O.COD_CONTRATO,
        NVL(D.DES_PESSOA, 'SEM CADASTRO NA V_DADOS_COLAB_AVT') AS DES_PESSOA,
        D.DATA_NASCIMENTO,
        D.ADMISSAO,
        D.DATA_DEMISSAO,
        D.COD_TIPO_ADMISSAO,
        D.DES_TIPO_ADMISSAO,
        D.SEXO,
        D.COD_EST_CIVIL,
        D.DES_EST_CIVIL,
        D.IND_DEFICIENCIA,
        D.COD_INSTRUCAO,
        D.DES_INSTRUCAO,
        D.COD_PAIS,
        D.COD_PAIS_NASCTO,
        D.COD_NACIONALIDADE,
        D.DES_NACIONALIDADE,
        D.COD_RACA_COR,
        D.DES_RACA_COR,

        CASE
            WHEN AFO.COD_CONTRATO IS NOT NULL THEN 1
            ELSE 0
        END AS IND_AFASTADO_OFICIAL,

        CASE
            WHEN AFO.COD_CONTRATO IS NULL
             AND FER.COD_CONTRATO IS NOT NULL THEN 1
            ELSE 0
        END AS IND_FERIAS_REF,

        CASE
            WHEN AFO.COD_CONTRATO IS NOT NULL THEN 1
            WHEN FER.COD_CONTRATO IS NOT NULL THEN 7
            ELSE 0
        END AS COD_AFAST,

        CASE
            WHEN AFO.COD_CONTRATO IS NOT NULL THEN 'AFASTADO'
            WHEN FER.COD_CONTRATO IS NOT NULL THEN 'EM FÉRIAS'
            ELSE 'EM ATIVIDADE'
        END AS STATUS_AFAST,

        O.COD_ORGANOGRAMA,
        O.COD_UNIDADE,
        O.DES_UNIDADE,
        O.COD_REDE_LOCAL,
        CASE
            WHEN O.COD_REDE_LOCAL = 1  THEN 'ADMINISTRAÇÃO'
            WHEN O.COD_REDE_LOCAL = 13 THEN 'LOGÍSTICA'
            WHEN O.COD_REDE_LOCAL = 10 THEN 'GRAZZIOTIN'
            WHEN O.COD_REDE_LOCAL = 30 THEN 'PORMENOS'
            WHEN O.COD_REDE_LOCAL = 40 THEN 'FRANCO GIORGI'
            WHEN O.COD_REDE_LOCAL = 50 THEN 'TOTTAL'
            WHEN O.COD_REDE_LOCAL = 70 THEN 'GZT STORE'
            ELSE O.DES_REDE_LOCAL
        END AS DES_REDE_LOCAL,

        O.COD_EMP,
        O.DES_EMPRESA,
        D.COD_UF,

        P.REFERENCIA,
        TRUNC(MONTHS_BETWEEN(P.REFERENCIA, D.DATA_NASCIMENTO) / 12) AS IDADE_REF,
        FLOOR(MONTHS_BETWEEN(P.REFERENCIA, D.ADMISSAO)) AS TEMPO_MESES_EMPRESA

    FROM DADOS_ATIVOS_REF D
    INNER JOIN ORG_REF O
        ON O.COD_CONTRATO = D.COD_CONTRATO
    LEFT JOIN AFASTADOS_OFICIAL_REF AFO
        ON AFO.COD_CONTRATO = D.COD_CONTRATO
    LEFT JOIN FERIAS_REF FER
        ON FER.COD_CONTRATO = D.COD_CONTRATO
    CROSS JOIN PARAMS P
),

BASE_FILTRADA AS (
    SELECT
        B.*,
        TRIM(UPPER(B.COD_UF)) AS COD_UF_RESIDENCIA
    FROM BASE B
    CROSS JOIN PARAMS P
    WHERE P.REDE_EMPRESA = 8
       OR B.COD_REDE_LOCAL = P.REDE_EMPRESA
),

/* Futuras admissões continuam vindo da view, pois ainda não estão no organograma vigente. */
FUTUROS_ADMITIDOS AS (
    SELECT COUNT(DISTINCT D.COD_CONTRATO) AS TOTAL_FUTUROS_ADMITIDOS
    FROM DADOS_VIEW D
    CROSS JOIN PARAMS P
    WHERE D.COD_EMP_VIEW = 8
      AND TRUNC(D.ADMISSAO) > P.REFERENCIA
      AND (
             P.REDE_EMPRESA = 8
          OR (
                REGEXP_LIKE(TRIM(TO_CHAR(D.COD_REDE_LOCAL_VIEW)), '^[0-9]+$')
            AND TO_NUMBER(TRIM(TO_CHAR(D.COD_REDE_LOCAL_VIEW))) = P.REDE_EMPRESA
             )
      )
),

RELACAO_GERAL AS (
    SELECT
        CASE
            WHEN MAX(P.REDE_EMPRESA) = 8 THEN TO_CHAR(MAX(B.COD_EMP))
            ELSE TO_CHAR(MAX(B.COD_REDE_LOCAL))
        END AS REDE_LOCAL,

        CASE
            WHEN MAX(P.REDE_EMPRESA) = 8 THEN MAX(B.DES_EMPRESA)
            ELSE MAX(B.DES_REDE_LOCAL)
        END AS DES_LOCAL,

        /* =========================
           FAIXA ETÁRIA
        ========================= */
        SUM(CASE WHEN IDADE_REF <= 18 THEN 1 ELSE 0 END) AS FAIXA_ATE_18_ANOS,
        SUM(CASE WHEN IDADE_REF > 18 AND IDADE_REF <= 21 THEN 1 ELSE 0 END) AS FAIXA_18_A_21_ANOS,
        SUM(CASE WHEN IDADE_REF > 21 AND IDADE_REF <= 25 THEN 1 ELSE 0 END) AS FAIXA_21_A_25_ANOS,
        SUM(CASE WHEN IDADE_REF > 25 AND IDADE_REF <= 30 THEN 1 ELSE 0 END) AS FAIXA_25_A_30_ANOS,
        SUM(CASE WHEN IDADE_REF > 30 AND IDADE_REF <= 40 THEN 1 ELSE 0 END) AS FAIXA_30_A_40_ANOS,
        SUM(CASE WHEN IDADE_REF > 40 AND IDADE_REF <= 50 THEN 1 ELSE 0 END) AS FAIXA_40_A_50_ANOS,
        SUM(CASE WHEN IDADE_REF > 50 THEN 1 ELSE 0 END) AS FAIXA_ACIMA_50_ANOS,
        SUM(CASE WHEN IDADE_REF IS NULL THEN 1 ELSE 0 END) AS FAIXA_SEM_DATA_NASCIMENTO,

        /* =========================
           SEXO
        ========================= */
        SUM(CASE WHEN UPPER(SEXO) IN ('M', 'MASCULINO') THEN 1 ELSE 0 END) AS SEXO_MASCULINO,
        SUM(CASE WHEN UPPER(SEXO) IN ('F', 'FEMININO') THEN 1 ELSE 0 END) AS SEXO_FEMININO,

        /* =========================
           ESTADO CIVIL
        ========================= */
        SUM(CASE WHEN UPPER(DES_EST_CIVIL) LIKE 'SOLTEIR%' THEN 1 ELSE 0 END) AS EST_CIVIL_SOLTEIRO,
        SUM(CASE WHEN UPPER(DES_EST_CIVIL) LIKE 'CASAD%' THEN 1 ELSE 0 END) AS EST_CIVIL_CASADO,
        SUM(CASE WHEN UPPER(DES_EST_CIVIL) LIKE 'SEPARAD%' THEN 1 ELSE 0 END) AS EST_CIVIL_SEPARADO,
        SUM(CASE WHEN UPPER(DES_EST_CIVIL) LIKE 'DIVORCIAD%' THEN 1 ELSE 0 END) AS EST_CIVIL_DIVORCIADO,
        SUM(CASE WHEN UPPER(DES_EST_CIVIL) LIKE 'VIÚV%'
               OR UPPER(DES_EST_CIVIL) LIKE 'VIUV%' THEN 1 ELSE 0 END) AS EST_CIVIL_VIUVO,
        SUM(CASE WHEN UPPER(DES_EST_CIVIL) LIKE 'UNIÃO ESTÁVEL%'
               OR UPPER(DES_EST_CIVIL) LIKE 'UNIAO ESTAVEL%' THEN 1 ELSE 0 END) AS EST_CIVIL_UNIAO_ESTAVEL,

        /* =========================
           ESCOLARIDADE POR CÓDIGO
        ========================= */
        SUM(CASE WHEN COD_INSTRUCAO = 1 THEN 1 ELSE 0 END) AS ESC_ANALFABETO,
        SUM(CASE WHEN COD_INSTRUCAO IN (2, 3, 4) THEN 1 ELSE 0 END) AS ESC_FUNDAMENTAL_INCOMPLETO,
        SUM(CASE WHEN COD_INSTRUCAO = 5 THEN 1 ELSE 0 END) AS ESC_FUNDAMENTAL_COMPLETO,
        SUM(CASE WHEN COD_INSTRUCAO = 6 THEN 1 ELSE 0 END) AS ESC_MEDIO_INCOMPLETO,
        SUM(CASE WHEN COD_INSTRUCAO = 7 THEN 1 ELSE 0 END) AS ESC_MEDIO_COMPLETO,
        SUM(CASE WHEN COD_INSTRUCAO = 8 THEN 1 ELSE 0 END) AS ESC_SUPERIOR_INCOMPLETO,
        SUM(CASE WHEN COD_INSTRUCAO = 9 THEN 1 ELSE 0 END) AS ESC_SUPERIOR_COMPLETO,
        SUM(CASE WHEN COD_INSTRUCAO = 10 THEN 1 ELSE 0 END) AS ESC_POS_GRAD_INCOMPLETA,
        SUM(CASE WHEN COD_INSTRUCAO = 11 THEN 1 ELSE 0 END) AS ESC_POS_GRAD_COMPLETA,
        SUM(CASE WHEN COD_INSTRUCAO = 12 THEN 1 ELSE 0 END) AS ESC_MESTRADO_INCOMPLETO,
        SUM(CASE WHEN COD_INSTRUCAO = 13 THEN 1 ELSE 0 END) AS ESC_MESTRADO_COMPLETO,
        SUM(CASE WHEN COD_INSTRUCAO = 14 THEN 1 ELSE 0 END) AS ESC_DOUTORADO_INCOMPLETO,
        SUM(CASE WHEN COD_INSTRUCAO = 15 THEN 1 ELSE 0 END) AS ESC_DOUTORADO_COMPLETO,
        SUM(CASE WHEN COD_INSTRUCAO = 16 THEN 1 ELSE 0 END) AS ESC_POS_DOUTORADO_INCOMPLETO,
        SUM(CASE WHEN COD_INSTRUCAO = 17 THEN 1 ELSE 0 END) AS ESC_POS_DOUTORADO_COMPLETO,
        SUM(CASE WHEN COD_INSTRUCAO IS NULL OR COD_INSTRUCAO NOT BETWEEN 1 AND 17 THEN 1 ELSE 0 END) AS ESC_INSTRUCAO_NAO_MAPEADA,

        /* =========================
           TEMPO DE EMPRESA
        ========================= */
        NVL(SUM(CASE WHEN B.TEMPO_MESES_EMPRESA < 12 THEN 1 ELSE 0 END), 0) AS TEMPO_ABAIXO_1_ANO,
        NVL(SUM(CASE WHEN B.TEMPO_MESES_EMPRESA >= 12 AND B.TEMPO_MESES_EMPRESA < 24 THEN 1 ELSE 0 END), 0) AS TEMPO_1_A_2_ANOS,
        NVL(SUM(CASE WHEN B.TEMPO_MESES_EMPRESA >= 24 AND B.TEMPO_MESES_EMPRESA < 60 THEN 1 ELSE 0 END), 0) AS TEMPO_2_A_5_ANOS,
        NVL(SUM(CASE WHEN B.TEMPO_MESES_EMPRESA >= 60 AND B.TEMPO_MESES_EMPRESA < 120 THEN 1 ELSE 0 END), 0) AS TEMPO_5_A_10_ANOS,
        NVL(SUM(CASE WHEN B.TEMPO_MESES_EMPRESA >= 120 AND B.TEMPO_MESES_EMPRESA < 240 THEN 1 ELSE 0 END), 0) AS TEMPO_10_A_20_ANOS,
        NVL(SUM(CASE WHEN B.TEMPO_MESES_EMPRESA >= 240 AND B.TEMPO_MESES_EMPRESA < 360 THEN 1 ELSE 0 END), 0) AS TEMPO_20_A_30_ANOS,
        NVL(SUM(CASE WHEN B.TEMPO_MESES_EMPRESA >= 360 AND B.TEMPO_MESES_EMPRESA < 480 THEN 1 ELSE 0 END), 0) AS TEMPO_30_A_40_ANOS,
        NVL(SUM(CASE WHEN B.TEMPO_MESES_EMPRESA >= 480 THEN 1 ELSE 0 END), 0) AS TEMPO_ACIMA_40_ANOS,
        NVL(SUM(CASE WHEN B.TEMPO_MESES_EMPRESA IS NULL THEN 1 ELSE 0 END), 0) AS TEMPO_EMPRESA_SEM_DATA,

        /* =========================
           EMPREGOS
        ========================= */
        SUM(CASE WHEN COD_TIPO_ADMISSAO = 1 THEN 1 ELSE 0 END) AS PRIMEIRO_EMPREGO,
        SUM(CASE WHEN COD_TIPO_ADMISSAO <> 1 OR COD_TIPO_ADMISSAO IS NULL THEN 1 ELSE 0 END) AS EMPREGOS_ANTERIORES,

        /* =========================
           RAÇA / COR
        ========================= */
        SUM(CASE WHEN COD_RACA_COR = 1 THEN 1 ELSE 0 END) AS RACA_INDIGENA,
        SUM(CASE WHEN COD_RACA_COR = 2 THEN 1 ELSE 0 END) AS RACA_BRANCA,
        SUM(CASE WHEN COD_RACA_COR = 4 THEN 1 ELSE 0 END) AS RACA_PRETA,
        SUM(CASE WHEN COD_RACA_COR = 6 THEN 1 ELSE 0 END) AS RACA_AMARELA,
        SUM(CASE WHEN COD_RACA_COR = 8 THEN 1 ELSE 0 END) AS RACA_PARDA,
        SUM(CASE WHEN COD_RACA_COR = 9 THEN 1 ELSE 0 END) AS RACA_NAO_INFORMADO,
        SUM(CASE WHEN COD_RACA_COR IS NULL OR COD_RACA_COR NOT IN (1, 2, 4, 6, 8, 9) THEN 1 ELSE 0 END) AS RACA_NAO_MAPEADA,

        /* =========================
           NACIONALIDADE
        ========================= */
        SUM(CASE WHEN COD_NACIONALIDADE = 10 THEN 1 ELSE 0 END) AS NAC_BRASILEIRO,
        SUM(CASE WHEN COD_NACIONALIDADE = 20 THEN 1 ELSE 0 END) AS NAC_NATURALIZADO_BRASILEIRO,
        SUM(CASE WHEN COD_NACIONALIDADE IS NOT NULL AND COD_NACIONALIDADE NOT IN (10, 20) THEN 1 ELSE 0 END) AS NAC_ESTRANGEIRO,
        SUM(CASE WHEN COD_NACIONALIDADE IS NULL THEN 1 ELSE 0 END) AS NAC_NAO_INFORMADA,

        /* =========================
           LOCALIZAÇÃO POR UF RESIDENCIAL
        ========================= */
        SUM(CASE WHEN B.COD_UF_RESIDENCIA = 'RS' THEN 1 ELSE 0 END) AS UF_RS,
        SUM(CASE WHEN B.COD_UF_RESIDENCIA = 'SC' THEN 1 ELSE 0 END) AS UF_SC,
        SUM(CASE WHEN B.COD_UF_RESIDENCIA = 'PR' THEN 1 ELSE 0 END) AS UF_PR,
        SUM(CASE WHEN B.COD_UF_RESIDENCIA IS NULL OR B.COD_UF_RESIDENCIA NOT IN ('RS', 'SC', 'PR') THEN 1 ELSE 0 END) AS UF_NAO_MAPEADA,

        SUM(CASE WHEN B.COD_UF_RESIDENCIA = 'RS' AND B.IND_AFASTADO_OFICIAL = 1 THEN 1 ELSE 0 END) AS UF_RS_AFASTADOS,
        SUM(CASE WHEN B.COD_UF_RESIDENCIA = 'SC' AND B.IND_AFASTADO_OFICIAL = 1 THEN 1 ELSE 0 END) AS UF_SC_AFASTADOS,
        SUM(CASE WHEN B.COD_UF_RESIDENCIA = 'PR' AND B.IND_AFASTADO_OFICIAL = 1 THEN 1 ELSE 0 END) AS UF_PR_AFASTADOS,
        SUM(CASE WHEN (B.COD_UF_RESIDENCIA IS NULL OR B.COD_UF_RESIDENCIA NOT IN ('RS', 'SC', 'PR')) AND B.IND_AFASTADO_OFICIAL = 1 THEN 1 ELSE 0 END) AS UF_NAO_MAPEADA_AFASTADOS,

        /* =========================
           TOTAIS GERAIS
        ========================= */
        COUNT(DISTINCT B.COD_CONTRATO) AS TOTAL_FUNCIONARIOS,

        COUNT(DISTINCT CASE
            WHEN B.IND_AFASTADO_OFICIAL = 0
             AND B.IND_FERIAS_REF = 0
            THEN B.COD_CONTRATO
        END) AS TOTAL_TRABALHANDO,

        COUNT(DISTINCT CASE
            WHEN B.IND_FERIAS_REF = 1
            THEN B.COD_CONTRATO
        END) AS TOTAL_EM_FERIAS,

        COUNT(DISTINCT CASE
            WHEN B.IND_AFASTADO_OFICIAL = 1
            THEN B.COD_CONTRATO
        END) AS TOTAL_AFASTADOS,

        MAX(F.TOTAL_FUTUROS_ADMITIDOS) AS TOTAL_FUTUROS_ADMITIDOS,
        P.REFERENCIA AS REFERENCIA

    FROM BASE_FILTRADA B
    CROSS JOIN FUTUROS_ADMITIDOS F
    CROSS JOIN PARAMS P
)

