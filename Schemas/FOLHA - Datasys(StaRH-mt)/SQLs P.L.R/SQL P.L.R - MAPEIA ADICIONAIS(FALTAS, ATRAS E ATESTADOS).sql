SELECT
    TB.COD_CONTRATO,
    TB.NOME_COLABORADOR,
    TB.DT_ADMISSAO,
    TB.DT_DEMISSAO,
    TB.NOTA_1,
    TB.MESES,
    TB.MOTIVO_DEMISSAO,
    TB.CARGO,
    TB.LOJA_CIDADE,
    TB.SALARIO,
    TB.SAL_PROP,
    ROUND(NVL(SUM(B.QTDE_VD), 0))  AS "ATESTADOS_QTD_%",
    ROUND(NVL(SUM(B.VALOR_VD), 0)) AS VLR_ATESTADOS,
    TB.NOTA_2,
    TB.REDE
FROM TMP_DEM_COM_DIREITO_PLR TB
JOIN RHFP1006 B
  ON B.COD_CONTRATO = TB.COD_CONTRATO
JOIN RHFP1003 R
  ON R.COD_MESTRE_EVENTO = B.COD_MESTRE_EVENTO
WHERE TB.COD_CONTRATO IN (
    397069, 397440, 387518, 392897, 393982, 394321, 394646, 394982, 395114, 395985,
    396431, 396698, 396898, 397134, 384615, 393899, 396370, 396730, 386537, 386759,
    388841, 389212, 391799, 392967, 393244, 393787, 394068, 394557, 394610, 394683,
    394915, 395360, 395425, 395728, 396356, 396647, 396648, 396997, 397078, 397136,
    384163, 385214, 386260, 387216, 389218, 389703, 389982, 391283, 391478, 391719,
    392115, 392357, 392548, 392710, 392722, 393767, 394326, 394330, 394475, 394789,
    394874, 395059, 395168, 395425, 395516, 395682, 395699, 395945, 395994, 396110,
    396215, 396302, 396317, 396357, 396365, 396377, 396449, 396582, 396627, 396654,
    396797, 396858, 396938, 396984, 397007, 397093, 397148, 397171, 397190, 397212,
    397243, 397245, 397250, 397252, 397271, 397273, 397278, 397283, 397284, 397286,
    397289, 397291, 397293, 397295, 397296, 397299, 397300, 397302, 397305, 397307,
    397308, 397310, 397311, 397312, 397313, 397314, 397315, 397316, 397317, 397318,
    397319, 397320, 397321, 397322, 397323, 397324, 397325, 397326, 397327, 397328
)
  AND B.COD_MESTRE_EVENTO IN (
      17434, 17503, 17581, 17644, 17712, 17804,
      17870, 17962, 18020, 18103, 18171, 18236
  )
  AND B.COD_VD IN (631, 632, 831, 832, 833, 897)
  AND R.DATA_REFERENCIA BETWEEN TO_DATE('01/01/2025', 'DD/MM/YYYY')
                            AND TO_DATE('30/04/2026', 'DD/MM/YYYY')
GROUP BY
    TB.COD_CONTRATO,
    TB.NOME_COLABORADOR,
    TB.DT_ADMISSAO,
    TB.DT_DEMISSAO,
    TB.NOTA_1,
    TB.MESES,
    TB.MOTIVO_DEMISSAO,
    TB.CARGO,
    TB.LOJA_CIDADE,
    TB.SALARIO,
    TB.SAL_PROP,
    TB.NOTA_2,
    TB.REDE
ORDER BY TB.COD_CONTRATO;
