SELECT S.CODSIT,
       C.DESSIT,
       C.TIPSIT,
       C.CONABS,
       COUNT(*) AS QTD_REGISTROS,
       COUNT(DISTINCT S.NUMEMP || '|' || S.TIPCOL || '|' || S.NUMCAD) AS QTD_COLABORADORES,
       MIN(S.QTDHOR) AS MENOR_QTDHOR,
       MAX(S.QTDHOR) AS MAIOR_QTDHOR
  FROM SENIOR_RH.R066SIT S
  JOIN SENIOR_RH.R010SIT C
    ON C.CODSIT = S.CODSIT
 WHERE S.NUMEMP = 8
   AND S.DATAPU >= DATE '2026-09-01'
   AND S.DATAPU < DATE '2026-10-01'
 GROUP BY S.CODSIT, C.DESSIT, C.TIPSIT, C.CONABS
 ORDER BY C.CONABS, S.CODSIT;