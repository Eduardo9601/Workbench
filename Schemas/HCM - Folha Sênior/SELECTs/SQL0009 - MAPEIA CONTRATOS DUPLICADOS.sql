SELECT
    F.NUMEMP AS EMPRESA,
    F.TIPCOL,
    F.NUMCAD AS CONTRATO,
    F.NOMFUN AS FUNCIONARIO,
    --F.NUMCPF,
    F.SITAFA,
    F.DATADM,
    COUNT(*) OVER (PARTITION BY F.NUMCAD) AS QTD_DUPLICADOS
FROM R034FUN F
WHERE F.SITAFA <> 7
  AND F.TIPCOL = 1
  AND F.NUMCAD IN (
      SELECT F2.NUMCAD
      FROM R034FUN F2
      WHERE F2.SITAFA <> 7
        AND F2.TIPCOL = 1
      GROUP BY F2.NUMCAD
      HAVING COUNT(*) > 1
  )
ORDER BY F.NUMCAD, F.NUMEMP, F.NOMFUN;