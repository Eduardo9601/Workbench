WITH PARAMETROS AS (
    SELECT
        C.NUMEMP,
        C.CODCAL,
        C.PERREF,
        LAST_DAY(C.PERREF) AS DATA_REF
    FROM R044CAL C
    WHERE C.NUMEMP = 8
      AND C.CODCAL = 18591
),

COLAB_FOLHA AS (
    SELECT DISTINCT
        V.NUMEMP,
        V.TIPCOL,
        V.NUMCAD
    FROM R046VER V
    INNER JOIN PARAMETROS P
        ON P.NUMEMP = V.NUMEMP
       AND P.CODCAL = V.CODCAL
    WHERE V.TIPCOL = 1
),

SALARIOS AS (
    SELECT
        H.NUMEMP,
        H.TIPCOL,
        H.NUMCAD,
        H.VALSAL,
        H.TIPSAL,
        ROW_NUMBER() OVER (
            PARTITION BY
                H.NUMEMP,
                H.TIPCOL,
                H.NUMCAD
            ORDER BY
                H.DATALT DESC,
                H.SEQALT DESC
        ) AS RN
    FROM R038HSA H
    INNER JOIN COLAB_FOLHA CF
        ON CF.NUMEMP = H.NUMEMP
       AND CF.TIPCOL = H.TIPCOL
       AND CF.NUMCAD = H.NUMCAD
    CROSS JOIN PARAMETROS P
    WHERE H.DATALT <= P.DATA_REF
),

VERBAS AS (
    SELECT
        V.NUMEMP,
        V.TIPCOL,
        V.NUMCAD,

        SUM(CASE
            WHEN V.TABEVE = 1
             AND V.CODEVE = 1
            THEN V.VALEVE ELSE 0
        END) AS HORAS_NORMAIS,

        SUM(CASE
            WHEN V.TABEVE = 1
             AND V.CODEVE IN (220, 224)
            THEN V.VALEVE ELSE 0
        END) AS GRATIFICACAO,

        SUM(CASE
            WHEN V.TABEVE = 1
             AND V.CODEVE = 218
            THEN V.VALEVE ELSE 0
        END) AS ANTECIPACAO,

        SUM(CASE
            WHEN V.TABEVE = 1
             AND V.CODEVE = 962
            THEN V.VALEVE ELSE 0
        END) AS ANTECIPACAO_962,

        SUM(CASE
            WHEN V.TABEVE = 1
             AND V.CODEVE IN (222, 422)
            THEN V.VALEVE ELSE 0
        END) AS QUINQUENIO,

        SUM(CASE
            WHEN V.TABEVE = 1
             AND V.CODEVE IN (415, 1967)
            THEN V.VALEVE ELSE 0
        END) AS TRIENIO

    FROM R046VER V
    INNER JOIN PARAMETROS P
        ON P.NUMEMP = V.NUMEMP
       AND P.CODCAL = V.CODCAL
    WHERE V.TIPCOL = 1
    GROUP BY
        V.NUMEMP,
        V.TIPCOL,
        V.NUMCAD
)

SELECT
    F.NUMEMP,
    F.NUMCAD AS MATRICULA,
    F.NOMFUN AS COLABORADOR,

    F.CODCCU AS COD_CENTRO_CUSTO,
    CC.CCUTXT AS TEXTO_CENTRO_CUSTO,
    CC.NOMCCU AS DESCRICAO_CENTRO_CUSTO,

    CAR.TITCAR AS DESCRICAO_CARGO,

    S.VALSAL AS SALARIO_BASE,
    S.TIPSAL AS TIPO_SALARIO,

    NVL(V.HORAS_NORMAIS, 0)
        AS HORAS_NORMAIS_FOLHA,

    NVL(V.GRATIFICACAO, 0)
        AS GRATIFICACAO,

    NVL(V.ANTECIPACAO, 0)
        AS ANTECIPACAO,

    NVL(V.ANTECIPACAO_962, 0)
        AS ANTECIPACAO_ESPECIAL,

    NVL(V.QUINQUENIO, 0)
        AS QUINQUENIO,

    NVL(V.TRIENIO, 0)
        AS TRIENIO

FROM COLAB_FOLHA CF

INNER JOIN R034FUN F
    ON F.NUMEMP = CF.NUMEMP
   AND F.TIPCOL = CF.TIPCOL
   AND F.NUMCAD = CF.NUMCAD

LEFT JOIN R018CCU CC
    ON CC.NUMEMP = F.NUMEMP
   AND CC.CODCCU = F.CODCCU

LEFT JOIN R024CAR CAR
    ON CAR.ESTCAR = F.ESTCAR
   AND CAR.CODCAR = F.CODCAR

LEFT JOIN SALARIOS S
    ON S.NUMEMP = F.NUMEMP
   AND S.TIPCOL = F.TIPCOL
   AND S.NUMCAD = F.NUMCAD
   AND S.RN = 1

LEFT JOIN VERBAS V
    ON V.NUMEMP = F.NUMEMP
   AND V.TIPCOL = F.TIPCOL
   AND V.NUMCAD = F.NUMCAD
WHERE F.SITAFA <> 7
ORDER BY
    F.CODCCU,
    F.NOMFUN
