SELECT R046VER.NUMEMP AS EMPRESA,
       R030EMP.APEEMP AS NOME_EMPRESA,
       R046VER.NUMCAD AS CONTRATO,
       R034FUN.NOMFUN AS NOME,
       R046VER.CODCAL AS CALCULO_MESTRE,
       R044CAL.TIPCAL AS TIPO_CALCULO_EVENTO,
       R044CAL.PERREF AS REFERENCIA,
       R046VER.CODEVE AS EVENTO_VD,
       R008EVC.DESEVE AS DESCRICAO
  FROM SENIOR_RH.R046VER,
       SENIOR_RH.R030EMP,
       SENIOR_RH.R034FUN,
       SENIOR_RH.R044CAL,
       SENIOR_RH.R008EVC
 WHERE /*R046VER.VALEVE = 0*/
    R030EMP.NUMEMP = R046VER.NUMEMP
   AND R034FUN.NUMEMP = R046VER.NUMEMP
   AND R034FUN.TIPCOL = R046VER.TIPCOL
   AND R034FUN.NUMCAD = R046VER.NUMCAD
   AND R044CAL.NUMEMP = R046VER.NUMEMP
   AND R044CAL.CODCAL = R046VER.CODCAL
   AND R008EVC.CODTAB = R046VER.TABEVE
   AND R008EVC.CODEVE = R046VER.CODEVE